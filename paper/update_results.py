#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


def _load_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def _fmt_pct(x: float) -> str:
    return f"{x * 100:.1f}\\%"


def _fmt_s(x: float) -> str:
    return f"{x:.1f}"


def _find_match(aggregated: dict[str, Any], match_id: str) -> dict[str, Any]:
    for m in aggregated.get("matches", []):
        if m.get("id") == match_id:
            return m
    raise KeyError(f"Missing match id in results: {match_id}")


def _extract_agent_b_metrics(match_summary: dict[str, Any]) -> dict[str, float]:
    results = match_summary["summary"]["results"]
    n_games = int(match_summary["summary"]["match"]["n_games"])
    return {
        "win_rate": float(results["win_rate_agent_b"]),
        "over_budget_rate": float(results.get("over_budget_rate", results.get("timeout_rate", 0.0))),
        "avg_time_s": float(results["avg_game_time_s"]),
        "n_games": float(n_games),
    }


def _write(path: Path, content: str) -> None:
    path.write_text(content.rstrip() + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate LaTeX tables/macros from experiment results.")
    parser.add_argument("--results", type=str, default="paper/results/summary.json", help="Aggregated suite summary.json")
    args = parser.parse_args()

    results_path = Path(args.results)
    aggregated = _load_json(results_path)
    outdir = results_path.parent

    final_basic = _extract_agent_b_metrics(_find_match(aggregated, "final_vs_basic"))
    final_pro = _extract_agent_b_metrics(_find_match(aggregated, "final_vs_pro"))

    ablations = [
        ("Ghost Ball Only", "ablation_ghost_only_vs_basic"),
        ("Full System", "final_vs_basic"),
        ("w/o CMA-ES", "ablation_no_cma_vs_basic"),
        ("w/o Geometric Pruning", "ablation_no_pruning_vs_basic"),
        ("w/o Strategy/Safety", "ablation_no_strategy_vs_basic"),
        ("w/o Catastrophic Penalty", "ablation_no_catastrophic_vs_basic"),
    ]

    ablation_rows: list[tuple[str, dict[str, float]]] = []
    for label, mid in ablations:
        ablation_rows.append((label, _extract_agent_b_metrics(_find_match(aggregated, mid))))

    macros = "\n".join(
        [
            "% Auto-generated by paper/update_results.py. Do not edit by hand.",
            f"\\newcommand{{\\FinalWinVsBasic}}{{{_fmt_pct(final_basic['win_rate'])}}}",
            f"\\newcommand{{\\FinalWinVsPro}}{{{_fmt_pct(final_pro['win_rate'])}}}",
            f"\\newcommand{{\\FinalAvgTimeVsBasic}}{{{_fmt_s(final_basic['avg_time_s'])}}}",
            f"\\newcommand{{\\FinalAvgTimeVsPro}}{{{_fmt_s(final_pro['avg_time_s'])}}}",
            f"\\newcommand{{\\FinalOverBudgetVsBasic}}{{{_fmt_pct(final_basic['over_budget_rate'])}}}",
            f"\\newcommand{{\\FinalOverBudgetVsPro}}{{{_fmt_pct(final_pro['over_budget_rate'])}}}",
        ]
    )
    _write(outdir / "generated_results.tex", macros)

    winrate_table = "\n".join(
        [
            "% Auto-generated by paper/update_results.py. Do not edit by hand.",
            "\\begin{table}[t]",
            f"\\caption{{Win Rate Summary ($N$={int(final_basic['n_games'])} games per matchup)}}",
            "\\label{table_winrate}",
            "\\centering",
            "\\scriptsize",
            "\\setlength{\\tabcolsep}{3pt}",
            "\\renewcommand{\\arraystretch}{1.05}",
            "\\resizebox{\\columnwidth}{!}{%",
            "\\begin{tabular}{lccc}",
            "\\hline",
            "\\textbf{Ours vs.} & \\textbf{WR} & \\textbf{Avg. (s)} & \\textbf{Over-180s} \\\\",
            "\\hline",
            f"Basic & {_fmt_pct(final_basic['win_rate'])} & {_fmt_s(final_basic['avg_time_s'])} & {_fmt_pct(final_basic['over_budget_rate'])} \\\\",
            f"BasicPro & {_fmt_pct(final_pro['win_rate'])} & {_fmt_s(final_pro['avg_time_s'])} & {_fmt_pct(final_pro['over_budget_rate'])} \\\\",
            "\\hline",
            "\\end{tabular}",
            "}%",
            "\\end{table}",
        ]
    )
    _write(outdir / "generated_table_winrate.tex", winrate_table)

    ablation_n_games = int(ablation_rows[0][1]["n_games"]) if ablation_rows else 0
    ablation_lines = [
        "% Auto-generated by paper/update_results.py. Do not edit by hand.",
        "\\begin{table}[t]",
        f"\\caption{{Ablation Study (vs. BasicAgent, $N$={ablation_n_games} games each)}}",
        "\\label{table_ablation}",
        "\\centering",
        "\\scriptsize",
        "\\setlength{\\tabcolsep}{3pt}",
        "\\renewcommand{\\arraystretch}{1.05}",
        "\\resizebox{\\columnwidth}{!}{%",
        "\\begin{tabular}{p{2.3cm}ccc}",
        "\\hline",
        "\\textbf{Variant} & \\textbf{WR} & \\textbf{Avg. (s)} & \\textbf{Over-180s} \\\\",
        "\\hline",
    ]
    for label, m in ablation_rows:
        ablation_lines.append(
            f"{label} & {_fmt_pct(m['win_rate'])} & {_fmt_s(m['avg_time_s'])} & {_fmt_pct(m['over_budget_rate'])} \\\\"
        )
    ablation_lines += ["\\hline", "\\end{tabular}", "}%", "\\end{table}"]
    _write(outdir / "generated_table_ablation.tex", "\n".join(ablation_lines))

    print(f"Wrote `{outdir / 'generated_results.tex'}`")
    print(f"Wrote `{outdir / 'generated_table_winrate.tex'}`")
    print(f"Wrote `{outdir / 'generated_table_ablation.tex'}`")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
